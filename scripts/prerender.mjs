// Runs after `vite build` (see package.json "build"). Renders the public content pages to HTML
// and writes them into a module the Netlify edge function bundles, so search engines and link
// previews get the full page text without running JavaScript.
// Always writes the module (empty if anything fails), so a problem here never breaks a publish.
import { writeFileSync, rmSync } from 'node:fs';

const out = new URL('../netlify/edge-functions/lib/prerendered.ts', import.meta.url);
const pages = {};
try {
  const { render, PRERENDER_PATHS } = await import(new URL('../dist-ssr/entry.js', import.meta.url).href);
  for (const path of PRERENDER_PATHS) {
    const html = render(path);
    if (html) pages[path] = html;
  }
  console.log(`Pre-rendered ${Object.keys(pages).length} pages for search engines.`);
} catch (e) {
  console.warn('Pre-render skipped:', e?.message ?? e);
}
writeFileSync(
  out,
  `// Generated by scripts/prerender.mjs at build time. Do not edit.\nexport const PRERENDERED: Record<string, string> = ${JSON.stringify(pages)};\n`,
);
rmSync(new URL('../dist-ssr', import.meta.url), { recursive: true, force: true });
